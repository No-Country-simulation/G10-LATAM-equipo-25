from transformers import pipeline
import pandas as pd
from tqdm import tqdm

# Este modelo es el estándar actual para datasets con varios idiomas
analyzer_multi = pipeline(
    "sentiment-analysis",
    model="cardiffnlp/twitter-xlm-roberta-base-sentiment",
    tokenizer="cardiffnlp/twitter-xlm-roberta-base-sentiment",
    device=0 # Usa la GPU de Colab
)

def analizar_sentimiento_local(fila):
    if fila['is_faq'] == True:
        return "FAQ Educativo"

    texto = str(fila['reviews'])
    if not texto.strip():
        return "Neutral"

    try:
        resultado = analyzer_multi(texto, truncation=True, max_length=512)[0]
        label = resultado['label']

        if label == 'LABEL_0' or label == 'negative': return "Negativo"
        elif label == 'LABEL_1' or label == 'neutral': return "Neutral"
        elif label == 'LABEL_2' or label == 'positive': return "Positivo"
        else: return "Neutral"

    except Exception as e:
        return "Neutral"

# Usamos la barra de progreso (esta vez irá rapidísimo)
tqdm.pandas(desc="Procesando reseñas")
df_maestro['sentiment'] = df_maestro.progress_apply(analizar_sentimiento_local, axis=1)

nombre_final_sentimientos = 'Database_Motor_Final_Completada.csv'
df_maestro.to_csv(nombre_final_sentimientos, index=False)

from google.colab import files
