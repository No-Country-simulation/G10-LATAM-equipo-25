def limpiar_texto(texto):
    if not isinstance(texto, str): return ""
    texto = str(texto).lower()
    texto = re.sub(r'<.*?>', '', texto)
    texto = re.sub(r'[^\w\s]', '', texto)
    texto = re.sub(r'\s+', ' ', texto).strip()
    return texto

